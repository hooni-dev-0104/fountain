"""Opt-in PostgreSQL/file storage proof; full HTTP download requires --http-full.

Only a newly generated workspace and private temporary directory are used. The
default proves full storage byte equality and a real HTTP range, not a full HTTP
upload/download. A failed database cleanup preserves its referenced disk files.
"""
from __future__ import annotations

import argparse
import hashlib
import http.client
import json
import os
from pathlib import Path
import shutil
import stat
import sys
import tempfile
import threading
import time
import uuid

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from fountain.attachments import CHUNK_SIZE, MAX_FILE_SIZE, FileStorage
from fountain.auth import SESSION_COOKIE
from fountain.backup import PRIVATE_KINDS, restore_backup
from fountain.core import Store
from fountain.postgres import PostgresStore
from fountain.postgres_backup import create_postgres_backup
from fountain.server import create_server


def peak_memory():
    try:
        import resource
        value = resource.getrusage(resource.RUSAGE_SELF).ru_maxrss
        return value if sys.platform == 'darwin' else value * 1024
    except ImportError:
        return None


def pattern(index, length):
    seed = hashlib.sha256(str(index).encode()).digest()
    return seed * (length // len(seed)) + seed[:length % len(seed)]


def expected_range(start, end):
    result = bytearray()
    while start < end:
        index, relative = divmod(start, CHUNK_SIZE)
        length = min(end - start, CHUNK_SIZE - relative)
        seed = hashlib.sha256(str(index).encode()).digest()
        shift = relative % len(seed)
        result.extend((seed * ((shift + length + len(seed) - 1) // len(seed)))[shift:shift + length])
        start += length
    return bytes(result)


def database_config(path):
    descriptor = os.open(path, os.O_RDONLY | os.O_NOFOLLOW)
    with os.fdopen(descriptor, 'rb') as source:
        info = os.fstat(source.fileno())
        if not (stat.S_ISREG(info.st_mode) and info.st_uid == os.getuid()
                and stat.S_IMODE(info.st_mode) == 0o600):
            raise ValueError('Database configuration must be a private owner-owned 0600 file')
        content = source.read(65537)
    if len(content) > 65536:
        raise ValueError('Database configuration exceeds 64 KiB')
    configuration = json.loads(content)
    dsn = configuration.get('database_dsn') if isinstance(configuration, dict) else None
    if not isinstance(dsn, str) or not dsn.strip():
        raise ValueError('Database configuration requires database_dsn')
    return dsn


def progress(phase, **values):
    print(json.dumps({'phase': phase, **values}), flush=True)


def download(server, identity, cookie, size, expected, *, full=False):
    connection = http.client.HTTPConnection('127.0.0.1', server.server_port, timeout=300)
    try:
        headers = {'Cookie': cookie}
        # Include both adjacent chunks when a boundary exists.
        start = max(0, min(CHUNK_SIZE - 113, size - 513))
        end = min(size, start + 513)
        if not full:
            headers['Range'] = f'bytes={start}-{end - 1}'
        connection.request('GET', '/api/attachments/' + identity + '/download', headers=headers)
        response = connection.getresponse()
        assert response.status == (200 if full else 206), 'Unexpected HTTP download status'
        assert int(response.getheader('Content-Length')) == (size if full else end - start)
        assert response.getheader('Cache-Control') == 'no-store'
        if not full:
            assert response.getheader('Content-Range') == f'bytes {start}-{end - 1}/{size}'
            assert response.read(514) == expected_range(start, end), 'HTTP range differs from generated bytes'
            return {'start': start, 'end': end, 'crossed_chunk_boundary': start < CHUNK_SIZE < end}
        digest, total = hashlib.sha256(), 0
        while data := response.read(65536):
            digest.update(data)
            total += len(data)
            if total % (128 * CHUNK_SIZE) == 0:
                progress('http_full_download', read=total)
        assert total == size and digest.hexdigest() == expected, 'Full HTTP checksum mismatch'
        return {'bytes': total, 'sha256': digest.hexdigest()}
    finally:
        connection.close()


def verify(args, dsn):
    started, initial_peak = time.monotonic(), peak_memory()
    folder = Path(tempfile.mkdtemp(prefix='fountain-pg-large-file-')).resolve()
    os.chmod(folder, 0o700)
    attachment_root = folder / 'attachment-files'
    namespace = 'large-file-verifier-' + uuid.uuid4().hex
    server = thread = store = None
    original_token = os.environ.pop('FOUNTAIN_ACCESS_TOKEN', None)
    report = {'size': args.size, 'workspace_id': namespace, 'storage_upload': False,
              'full_storage_read': False, 'http_upload': False, 'http_range': False,
              'http_full_download': False, 'backup_restore': False, 'chunk_size': CHUNK_SIZE,
              'storage_read_size': CHUNK_SIZE, 'http_read_size': 65536}
    try:
        server = create_server(port=0, database_url=dsn, workspace_id=namespace, attachment_root=attachment_root)
        store = server.application.store
        thread = threading.Thread(target=server.serve_forever, kwargs={'poll_interval': 0.05}, daemon=True)
        thread.start()
        auth = server.application.auth
        password = uuid.uuid4().hex + '-generated-verifier-password'
        auth.create_account('local', password)
        auth.enable_accounts()
        owner = store.get('member', 'local')
        cookie = SESSION_COOKIE + '=' + auth.login({'email': owner['email'], 'password': password})
        files = FileStorage(store)
        upload = files.begin({'name': 'generated-storage-verification.bin', 'size': args.size}, 'local')
        digest, offset, index = hashlib.sha256(), 0, 0
        progress('storage_upload', bytes=args.size, chunk_bytes=CHUNK_SIZE)
        while offset < args.size:
            data = pattern(index, min(CHUNK_SIZE, args.size - offset))
            digest.update(data)
            result = files.append(upload['id'], offset, data, 'local')
            offset += len(data)
            assert result['offset'] == offset
            index += 1
            if index % 128 == 0:
                progress('storage_upload', written=offset, seconds=round(time.monotonic() - started, 2))
        # Do not retain the final upload chunk during whole-file verification.
        if index:
            del data
        progress('storage_finalize', written=offset)
        attachment = files.complete(upload['id'], 'local')
        checksum = digest.hexdigest()
        assert attachment['size'] == args.size and attachment['sha256'] == checksum
        expected_chunks = (args.size + CHUNK_SIZE - 1) // CHUNK_SIZE
        with store.transaction():
            bytea_count = store._execute('SELECT count(*) FROM fountain_private.attachment_chunks WHERE workspace_id=%s',
                                        (namespace,), fetch='one')[0]
            manifests = store.list('attachment_chunk')
            assert bytea_count == 0, 'File bytes unexpectedly stored in PostgreSQL BYTEA'
            assert len(manifests) == expected_chunks
            layout = store.chunk_list(attachment['id'])
            assert len(layout) == expected_chunks
            actual, position = hashlib.sha256(), 0
            progress('full_storage_read', chunks=expected_chunks)
            for index, (offset, length, kind) in enumerate(layout):
                assert offset == position and kind == 'blob' and length == min(CHUNK_SIZE, args.size - position)
                data = store.chunk_read_range(attachment['id'], offset, 0, length)
                assert isinstance(data, bytes) and len(data) == length
                assert data == pattern(index, length), 'Storage chunk differs from generated bytes'
                actual.update(data)
                position += length
                if (index + 1) % 128 == 0:
                    progress('full_storage_read', read=position)
            assert position == args.size and actual.hexdigest() == checksum
        report.update(storage_upload=True, full_storage_read=True, chunks=expected_chunks,
                      bytea_rows=bytea_count, manifest_count=len(manifests), sha256=checksum)
        progress('http_range')
        if args.size:
            report['http_range_details'] = download(server, attachment['id'], cookie, args.size, checksum)
            report['http_range'] = True
        else:
            report['http_range_skipped_empty'] = True
        if args.http_full:
            progress('http_full_download', bytes=args.size)
            report['http_full_details'] = download(server, attachment['id'], cookie, args.size, checksum, full=True)
            report['http_full_download'] = True
        if args.backup:
            snapshot, restored = folder / 'portable.db', folder / 'restored.db'
            progress('backup', seconds=round(time.monotonic() - started, 2))
            create_postgres_backup(store, snapshot)
            progress('restore', backup_bytes=snapshot.stat().st_size)
            restore_backup(snapshot, restored)
            recovered = Store(restored)
            try:
                actual, size = hashlib.sha256(), 0
                for data in FileStorage(recovered).iter_bytes(attachment['id']):
                    assert len(data) <= 65536
                    actual.update(data)
                    size += len(data)
                assert size == args.size and actual.hexdigest() == checksum
                assert all(not recovered.list(kind) for kind in (*PRIVATE_KINDS, 'attachment_chunk'))
                absent = object()
                assert all(recovered.meta(key, absent) is absent for key in
                           ('attachment_file_root', 'attachment_file_gc_cursor', 'local_cache_binding'))
            finally:
                recovered.close()
            report.update(backup_restore=True, backup_bytes=snapshot.stat().st_size)
        final_peak = peak_memory()
        report.update(seconds=round(time.monotonic() - started, 2), peak_rss_bytes=final_peak,
                      peak_rss_growth_bytes=final_peak - initial_peak if final_peak is not None and initial_peak is not None else None)
        assert final_peak is not None and final_peak < 384 * 1024 * 1024, 'Peak RSS exceeds 384 MiB'
    finally:
        # Stop handlers before deleting references; leave bytes protected if any
        # shutdown/DB cleanup/close step fails. Never unlink live PG manifests.
        try:
            if server is not None:
                if thread is not None and thread.is_alive():
                    server.shutdown()
                server.server_close()
                if thread is not None:
                    thread.join()
            if store is None:
                store = PostgresStore(dsn, workspace_id=namespace, attachment_root=attachment_root)
            with store.transaction():
                for table in ('identity_mapping', 'attachment_chunks', 'entities', 'meta'):
                    store._execute(f'DELETE FROM fountain_private.{table} WHERE workspace_id=%s', (namespace,))
            store.close()
        except BaseException:
            if store is not None:
                try:
                    store.close()
                except Exception:
                    pass
            progress('cleanup_failed', preserved_private_directory=str(folder), workspace_id=namespace)
            raise RuntimeError('Cleanup failed; protected temporary bytes were preserved') from None
        else:
            try:
                shutil.rmtree(folder)
            except OSError:
                progress('cleanup_failed', preserved_private_directory=str(folder),
                         workspace_id=namespace, database_references_removed=True)
                raise RuntimeError('Temporary file cleanup failed after removing database references') from None
            report['cleanup'] = True
        finally:
            if original_token is not None:
                os.environ['FOUNTAIN_ACCESS_TOKEN'] = original_token
    return report


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--database-config', type=Path, required=True, help='Owner-owned 0600 JSON containing database_dsn')
    parser.add_argument('--size', type=int, default=8 * 1024 * 1024 + 123)
    parser.add_argument('--backup', action='store_true')
    parser.add_argument('--http-full', action='store_true', help='Also verify the potentially slow authenticated whole HTTP stream')
    parser.add_argument('--report', type=Path)
    args = parser.parse_args()
    if not 0 <= args.size <= MAX_FILE_SIZE:
        parser.error('size must be between 0 and 5,000,000,000 bytes')
    try:
        report = verify(args, database_config(args.database_config.expanduser().absolute()))
        if args.report:
            args.report.parent.mkdir(parents=True, exist_ok=True)
            args.report.write_text(json.dumps(report, indent=2) + '\n')
        progress('passed', **report)
    except Exception as error:
        # Driver/config errors must never dump SQL values or connection secrets.
        progress('failed', error_type=type(error).__name__)
        return 1
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
